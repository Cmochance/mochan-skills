class TierError(RuntimeError):
    """Structured error raised by a fetch tier."""

    def __init__(self, code: str, message: str):
        self.code = code
        super().__init__(message)


def cfg_int(mapping: Dict[str, Any], key: str, default: int) -> int:
    """Read an integer config value while preserving explicit 0."""
    val = mapping.get(key)
    if val is None or val == "":
        return default
    return int(val)


def cfg_float(mapping: Dict[str, Any], key: str, default: float) -> float:
    """Read a float config value while preserving explicit 0.0."""
    val = mapping.get(key)
    if val is None or val == "":
        return default
    return float(val)


def ensure_private_dir(path: Path) -> Path:
    """Create a directory with 0o700 permissions."""
    path.mkdir(parents=True, exist_ok=True, mode=0o700)
    try:
        os.chmod(path, 0o700)
    except OSError:
        pass
    return path


def atomic_write_private(path: Path, content: str) -> None:
    """Atomically write a UTF-8 file with 0o600 permissions."""
    ensure_private_dir(path.parent)
    fd, tmp_name = tempfile.mkstemp(dir=str(path.parent), prefix=f".{path.name}.")
    tmp_path = Path(tmp_name)
    try:
        os.chmod(tmp_path, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(content)
        os.replace(tmp_path, path)
    except BaseException:
        try:
            tmp_path.unlink(missing_ok=True)
        except OSError:
            pass
        raise


def parse_x_target(raw: str) -> TargetSpec:
    """Parse an X/Twitter URL or bare ASCII numeric status/article ID."""
    value = raw.strip()
    if not value:
        raise ValueError("Empty URL or tweet ID")

    if re.fullmatch(r"[0-9]+", value):
        return TargetSpec(
            tweet_id=value,
            user_hint="i",
            is_article_url=False,
            canonical_url=f"https://x.com/i/status/{value}",
        )

    if not re.match(r"^https?://", value, re.IGNORECASE):
        value = f"https://{value}"

    parsed = urllib.parse.urlparse(value)
    host = parsed.netloc.lower().split(":")[0]
    if host not in _X_HOSTS:
        raise ValueError(f"Unsupported host in URL: {parsed.netloc}")

    path = parsed.path.rstrip("/")
    # /<user>/status/<id>, /<user>/statuses/<id>, or /i/web/status/<id>
    m_status = re.match(r"^/(?:i/web|([^/]+))/status(?:es)?/([0-9]+)(?:/.*)?$", path)
    if m_status:
        user_hint = m_status.group(1) or "i"
        tweet_id = m_status.group(2)
        return TargetSpec(
            tweet_id=tweet_id,
            user_hint=user_hint,
            is_article_url=False,
            canonical_url=f"https://x.com/{user_hint}/status/{tweet_id}",
        )

    # /<user>/article/<id> or /i/article/<id> or /i/articles/<id>
    m_article = re.match(r"^/(?:i|([^/]+))/articles?/([0-9]+)(?:/.*)?$", path)
    if m_article:
        user_hint = m_article.group(1) or "i"
        article_id = m_article.group(2)
        return TargetSpec(
            tweet_id=article_id,
            user_hint=user_hint,
            is_article_url=True,
            canonical_url=f"https://x.com/{user_hint}/article/{article_id}",
        )

    raise ValueError(f"Could not extract status or article ID from: {raw}")


def is_likely_thread_head(post: PostItem) -> Tuple[bool, str]:
    """Detect whether a root post is likely the first post of a self-thread."""
    if post.replying_to_status:
        return False, ""
    replies = int(post.stats.get("replies") or 0)
    if replies <= 0:
        return False, ""

    text = (post.text or "").strip()
    for pat in _THREAD_STRONG_PATTERNS:
        m = pat.search(text)
        if m:
            return True, f"matched_marker:{m.group(0).strip()}"

    if re.search(r"[:：]\s*$", text):
        return True, "trailing_colon_with_replies"

    return False, ""


def _build_opener(proxy: Optional[str]) -> urllib.request.OpenerDirector:
    if proxy:
        return urllib.request.build_opener(
            urllib.request.ProxyHandler({"http": proxy, "https": proxy})
        )
    return urllib.request.build_opener()


def _curl_get_text(
    url: str,
    headers: Dict[str, str],
    timeout: int,
    proxy: str,
) -> Tuple[int, str]:
    cmd = [
        "/usr/bin/curl",
        "-sS",
        "-L",
        "--max-time",
        str(timeout),
        "--proxy",
        proxy,
        "-w",
        "\n%{http_code}",
    ]
    for k, v in headers.items():
        cmd.extend(["-H", f"{k}: {v}"])
    cmd.append(url)
    try:
        proc = subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=timeout + 5,
        )
    except (subprocess.SubprocessError, OSError) as exc:
        raise TierError("network_error", f"Proxy curl error fetching {url}: {exc}") from exc

    if proc.returncode != 0:
        err = (proc.stderr or "").strip() or f"exit code {proc.returncode}"
        raise TierError("network_error", f"Proxy curl failed for {url}: {err}")

    raw = proc.stdout or ""
    body, sep, code_str = raw.rpartition("\n")
    if not sep or not re.fullmatch(r"[0-9]{3}", code_str.strip()):
        raise TierError("network_error", f"Unexpected curl response for {url}")
    return int(code_str.strip()), body


def _decode_bytes(raw: bytes, charset: Optional[str]) -> str:
    enc = charset or "utf-8"
    try:
        return raw.decode(enc, errors="replace")
    except LookupError:
        return raw.decode("utf-8", errors="replace")


def _http_get_text(
    url: str,
    headers: Optional[Dict[str, str]] = None,
    timeout: int = 10,
    proxy: Optional[str] = None,
) -> Tuple[int, str]:
    hdrs = headers or {}
    if proxy and proxy.strip().lower().startswith(_SOCKS_PREFIXES):
        return _curl_get_text(url, hdrs, timeout, proxy.strip())

    req = urllib.request.Request(url, headers=hdrs)
    opener = _build_opener(proxy)
    try:
        with opener.open(req, timeout=timeout) as resp:
            raw = resp.read()
            return int(resp.status), _decode_bytes(raw, resp.headers.get_content_charset())
    except urllib.error.HTTPError as exc:
        body = ""
        if exc.fp:
            try:
                body = _decode_bytes(exc.fp.read(), exc.headers.get_content_charset() if exc.headers else None)
            except (OSError, http.client.HTTPException):
                body = ""
        return int(exc.code), body
    except (urllib.error.URLError, TimeoutError, http.client.HTTPException, OSError, LookupError, ValueError) as exc:
        reason = getattr(exc, "reason", None) or exc
        raise TierError("network_error", f"Network error fetching {url}: {reason}") from exc


def _render_fx_article_blocks(article_obj: Dict[str, Any]) -> Tuple[str, bool]:
    """Convert FxEmbed article.content.blocks into Markdown and note complex blocks."""
    content = article_obj.get("content") or {}
    blocks = content.get("blocks") or []
    parts: List[str] = []
    has_complex = False
    ordered_idx = 0

    for blk in blocks:
        if not isinstance(blk, dict):
            continue
        btype = str(blk.get("type") or "unstyled")
        text = str(blk.get("text") or "").strip()
        if btype == "atomic":
            has_complex = True
            continue
        if not text:
            continue
        if btype != "ordered-list-item":
            ordered_idx = 0

        if btype == "header-one":
            parts.append(f"# {text}")
        elif btype == "header-two":
            parts.append(f"## {text}")
        elif btype == "header-three":
            parts.append(f"### {text}")
        elif btype == "blockquote":
            parts.append(f"> {text}")
        elif btype == "unordered-list-item":
            parts.append(f"- {text}")
        elif btype == "ordered-list-item":
            ordered_idx += 1
            parts.append(f"{ordered_idx}. {text}")
        elif btype == "code-block":
            parts.append(f"```\n{text}\n```")
        else:
            parts.append(text)

    if article_obj.get("media_entities"):
        has_complex = True
    return "\n\n".join(parts), has_complex


def _parse_fx_tweet(tweet: Dict[str, Any]) -> PostItem:
    author = tweet.get("author") or {}
    media_list: List[MediaItem] = []
    media_obj = tweet.get("media") or {}

    for photo in media_obj.get("photos") or []:
        if isinstance(photo, dict) and photo.get("url"):
            media_list.append(
                MediaItem(
                    type="photo",
                    url=str(photo["url"]),
                    alt_text=str(photo.get("altText") or ""),
                )
            )
    for video in media_obj.get("videos") or []:
        if isinstance(video, dict) and video.get("url"):
            media_list.append(MediaItem(type=str(video.get("type") or "video"), url=str(video["url"])))
    if not media_list:
        for item in media_obj.get("all") or []:
            if isinstance(item, dict) and item.get("url"):
                media_list.append(
                    MediaItem(
                        type=str(item.get("type") or "media"),
                        url=str(item["url"]),
                        alt_text=str(item.get("altText") or ""),
                    )
                )

    article_data: Optional[ArticleData] = None
    raw_article = tweet.get("article")
    if isinstance(raw_article, dict):
        blocks_md, has_complex = _render_fx_article_blocks(raw_article)
        cover = ""
        cover_media = raw_article.get("cover_media") or {}
        if isinstance(cover_media, dict):
            cover = str(
                (cover_media.get("media_info") or {}).get("original_img_url")
                or cover_media.get("url")
                or ""
            )
        article_data = ArticleData(
            title=str(raw_article.get("title") or ""),
            preview_text=str(raw_article.get("preview_text") or ""),
            blocks_markdown=blocks_md,
            cover_url=cover,
            has_complex_blocks=has_complex,
        )

    quote_item = _parse_fx_tweet(tweet["quote"]) if isinstance(tweet.get("quote"), dict) else None
    text = str(tweet.get("text") or "")

    return PostItem(
        id=str(tweet.get("id") or ""),
        url=str(tweet.get("url") or f"https://x.com/i/status/{tweet.get('id', '')}"),
        author_id=str(author.get("id") or ""),
        author_handle=str(author.get("screen_name") or "unknown"),
        author_name=str(author.get("name") or author.get("screen_name") or "Unknown"),
        created_at=str(tweet.get("created_at") or ""),
        text=text,
        is_note_tweet=bool(tweet.get("is_note_tweet")) or len(text) > 280,
        article=article_data,
        quote=quote_item,
        media=media_list,
        poll=tweet.get("poll") if isinstance(tweet.get("poll"), dict) else None,
        replying_to=tweet.get("replying_to"),
        replying_to_status=str(tweet["replying_to_status"]) if tweet.get("replying_to_status") else None,
        stats={
            "replies": tweet.get("replies") or 0,
            "retweets": tweet.get("retweets") or 0,
            "likes": tweet.get("likes") or 0,
            "views": tweet.get("views"),
            "bookmarks": tweet.get("bookmarks"),
        },
    )


def fetch_tier1_fxembed(target: TargetSpec, config: Dict[str, Any]) -> PostItem:
    """Fetch a single status (including note_tweet and article metadata) via FxEmbed."""
    t1_cfg = config.get("tier1") or {}
    api_base = str(t1_cfg.get("api_base") or "https://api.fxtwitter.com").rstrip("/")
    timeout = cfg_int(t1_cfg, "timeout_seconds", 10)
    proxy = config.get("proxy")

    user_seg = target.user_hint or "i"
    endpoints = [
        f"{api_base}/{user_seg}/status/{target.tweet_id}",
        f"{api_base}/2/status/{target.tweet_id}",
    ]
    last_err = ""
    saw_404 = False
    for url in endpoints:
        status, body = _http_get_text(
            url,
            headers={"User-Agent": "x-post-reader/1.0 (+https://github.com/FxEmbed/FxEmbed)"},
            timeout=timeout,
            proxy=proxy,
        )
        payload: Optional[Dict[str, Any]] = None
        if body:
            try:
                parsed = json.loads(body)
                if isinstance(parsed, dict):
                    payload = parsed
            except json.JSONDecodeError as exc:
                if status == 200:
                    last_err = f"Invalid JSON from FxEmbed: {exc}"
                    continue

        if status == 200:
            if not isinstance(payload, dict):
                last_err = f"Unexpected non-object JSON from {url}"
                continue
            api_code = payload.get("code")
            if api_code == 404:
                raise TierError("not_found", f"Post {target.tweet_id} not found or private (API 404)")
            if api_code not in (None, 200):
                last_err = f"FxEmbed code {api_code}: {payload.get('message')}"
                continue
            tweet = payload.get("tweet") or payload.get("status")
            if isinstance(tweet, dict):
                return _parse_fx_tweet(tweet)
            last_err = f"Missing 'tweet'/'status' in FxEmbed response: {payload.get('message')}"
        elif status == 404:
            saw_404 = True
            if isinstance(payload, dict) and payload.get("code") == 404:
                raise TierError("not_found", f"Post {target.tweet_id} not found or private (HTTP 404)")
            last_err = f"HTTP 404 from {url}"
        else:
            last_err = f"HTTP {status} from {url}"

    if saw_404:
        raise TierError("not_found", f"Post {target.tweet_id} not found or private (HTTP 404)")
    raise TierError("tier1_failed", last_err or "FxEmbed request failed")


def walk_upstream_tier1(leaf: PostItem, config: Dict[str, Any]) -> Tuple[List[PostItem], bool]:
    """Follow replying_to_status backwards via Tier 1. Returns (posts_chrono, truncated)."""
    max_walk = cfg_int(config.get("tier1") or {}, "max_upstream_walk", 20)
    chain: List[PostItem] = [leaf]
    seen = {leaf.id}
    current = leaf
    truncated = False

    for _ in range(max_walk):
        parent_id = current.replying_to_status
        if not parent_id:
            break
        if parent_id in seen:
            truncated = True
            break
        parent_user = current.replying_to or "i"
        parent_target = TargetSpec(
            tweet_id=parent_id,
            user_hint=parent_user,
            is_article_url=False,
            canonical_url=f"https://x.com/{parent_user}/status/{parent_id}",
        )
        try:
            parent = fetch_tier1_fxembed(parent_target, config)
        except TierError:
            truncated = True
            break
        seen.add(parent.id)
        chain.append(parent)
        current = parent

    if current.replying_to_status and current.replying_to_status not in seen:
        truncated = True

    chain.reverse()
    return chain, truncated


def _strip_jina_preamble(text: str) -> str:
    """Extract body below Jina Reader metadata header when present."""
    marker = "Markdown Content:"
    idx = text.find(marker)
    if idx != -1 and idx < 600:
        return text[idx + len(marker) :].strip()
    lines = text.splitlines()
    body_start = 0
    for i, line in enumerate(lines[:10]):
        if re.match(r"^(?:Title|URL Source|Published Time|Warning):\s*", line):
            body_start = i + 1
        elif line.strip() == "":
            body_start = i + 1
        else:
            break
    return "\n".join(lines[body_start:]).strip() if body_start > 0 else text.strip()


def validate_not_login_wall(text: str, baseline_min_len: int = 40) -> Tuple[bool, str]:
    """Reject Jina Reader responses that only captured X's login wall, dead page, or empty shell."""
    normalized = (text or "").replace("’", "'").replace("‘", "'")
    body = _strip_jina_preamble(normalized)
    if not body:
        return False, "content_too_short"

    lowered = body.lower()
    for marker in _DEAD_PAGE_MARKERS:
        idx = lowered.find(marker)
        if idx != -1 and (len(body) < 1200 or idx < 400):
            return False, f"dead_page:{marker}"

    # Strip trailing unauthenticated X footer banner if actual article/post content precedes it
    if len(body) > 800:
        tail_start = max(len(body) - 400, 0)
        footer_pos = lowered.find("don't miss what's happening", tail_start)
        if footer_pos != -1:
            body = body[:footer_pos].strip()
            lowered = body.lower()

    if len(body) < max(baseline_min_len, 40):
        return False, "content_too_short"

    for marker in _LOGIN_WALL_MARKERS:
        idx = lowered.find(marker)
        if idx != -1 and (len(body) < 800 or idx < 350):
            return False, f"login_wall:{marker}"

    return True, ""


def fetch_tier2_jina(target_url: str, config: Dict[str, Any], baseline_min_len: int = 40) -> str:
    """Fetch rendered Markdown via Jina Reader and validate against X login-wall shells."""
    t2_cfg = config.get("tier2") or {}
    if not t2_cfg.get("enabled", True):
        raise TierError("tier2_disabled", "Tier 2 is disabled in configuration")

    jina_base = str(t2_cfg.get("jina_base") or "https://r.jina.ai").rstrip("/")
    timeout = cfg_int(t2_cfg, "jina_timeout_seconds", 30)
    api_key = str(t2_cfg.get("jina_api_key") or os.environ.get("JINA_API_KEY") or "").strip()
    proxy = config.get("proxy")

    headers = {
        "User-Agent": "x-post-reader/1.0",
        "Accept": "text/plain",
        "X-Timeout": str(timeout),
        "X-Retain-Images": "all",
    }
    if api_key:
        headers["Authorization"] = f"Bearer {api_key}"

    request_url = f"{jina_base}/{target_url}"
    status, body = _http_get_text(request_url, headers=headers, timeout=timeout + 10, proxy=proxy)
    if status != 200:
        raise TierError("tier2_http_error", f"Jina Reader returned HTTP {status}")

    ok, reason = validate_not_login_wall(body, baseline_min_len=baseline_min_len)
    if not ok:
        raise TierError("tier2_login_wall", f"Tier 2 returned invalid/login-wall content ({reason})")

    return body.strip()


def _state_dir_path(config: Dict[str, Any]) -> Path:
    return Path(os.path.expanduser(str(config.get("state_dir") or "~/.cache/x-post-reader/state")))


def _state_file_path(config: Dict[str, Any]) -> Path:
    return _state_dir_path(config) / "tier3_state.json"


def _state_lock_path(config: Dict[str, Any]) -> Path:
    return _state_dir_path(config) / "tier3_state.lock"


def _load_tier3_state(config: Dict[str, Any]) -> Dict[str, Any]:
    path = _state_file_path(config)
    if not path.exists():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else {}
    except (OSError, json.JSONDecodeError):
        return {}


def _save_tier3_state(config: Dict[str, Any], state: Dict[str, Any]) -> None:
    atomic_write_private(_state_file_path(config), json.dumps(state, indent=2))


class _StateFileLock:
    """Advisory exclusive file lock for Tier 3 rate-limit & circuit-breaker state."""

    def __init__(self, lock_path: Path):
        self._lock_path = lock_path
        self._fd: Optional[int] = None

    def __enter__(self) -> "_StateFileLock":
        ensure_private_dir(self._lock_path.parent)
        self._fd = os.open(str(self._lock_path), os.O_CREAT | os.O_RDWR, 0o600)
        try:
            os.chmod(self._lock_path, 0o600)
        except OSError:
            pass
        fcntl.flock(self._fd, fcntl.LOCK_EX)
        return self

    def __exit__(self, exc_type: Any, exc: Any, tb: Any) -> None:
        if self._fd is not None:
            try:
                fcntl.flock(self._fd, fcntl.LOCK_UN)
            finally:
                os.close(self._fd)
                self._fd = None


def _resolve_twitter_bin(t3_cfg: Dict[str, Any]) -> Tuple[Optional[str], str]:
    raw_bin = str(t3_cfg.get("twitter_bin") or "~/.local/bin/twitter").strip()
    is_default = raw_bin == "~/.local/bin/twitter"
    expanded = os.path.expanduser(raw_bin)
    candidate = Path(expanded)

    if not candidate.exists():
        if is_default:
            which_hit = shutil.which("twitter")
            if which_hit:
                candidate = Path(which_hit)
                expanded = which_hit
            else:
                return None, f"twitter_cli_missing:{expanded}"
        else:
            return None, f"twitter_cli_missing:{expanded}"

    if not (candidate.is_file() and os.access(candidate, os.X_OK)):
        return None, f"twitter_cli_not_executable:{expanded}"
    return str(candidate), ""


def _ensure_browser_cookie3_stub(config: Dict[str, Any]) -> Path:
    stub_dir = _state_dir_path(config) / "py_stub"
    stub_file = stub_dir / "browser_cookie3.py"
    if not stub_file.exists() or stub_file.read_text(encoding="utf-8") != _BROWSER_COOKIE3_STUB:
        atomic_write_private(stub_file, _BROWSER_COOKIE3_STUB)
    return stub_dir


def check_tier3_readiness(config: Dict[str, Any]) -> Tuple[bool, str]:
    """Check whether Tier 3 can be invoked safely without touching main browser cookies."""
    t3_cfg = config.get("tier3") or {}
    if not t3_cfg.get("enabled", True):
        return False, "tier3_disabled"

    twitter_bin, bin_err = _resolve_twitter_bin(t3_cfg)
    if not twitter_bin:
        return False, bin_err

    state = _load_tier3_state(config)
    cooldown_until = float(state.get("cooldown_until") or 0)
    now = time.time()
    if cooldown_until > now:
        remaining = int(cooldown_until - now)
        return False, f"circuit_breaker_open:{remaining}s"

    cookie_source = str(t3_cfg.get("cookie_source") or "config_file").strip().lower()
    if cookie_source == "config_file":
        auth_token = str(t3_cfg.get("auth_token") or "").strip()
        ct0 = str(t3_cfg.get("ct0") or "").strip()
        if not auth_token or not ct0 or auth_token.startswith("<") or ct0.startswith("<"):
            return False, "alt_account_cookie_not_configured"
        return True, "config_file"

    if cookie_source == "env":
        auth_token = str(os.environ.get("TWITTER_AUTH_TOKEN") or "").strip()
        ct0 = str(os.environ.get("TWITTER_CT0") or "").strip()
        if not auth_token or not ct0 or auth_token.startswith("<") or ct0.startswith("<"):
            return False, "env_cookie_not_configured"
        return True, "env"

    if cookie_source == "browser":
        return True, f"browser:{t3_cfg.get('browser_name') or 'auto'}"

    return False, f"invalid_cookie_source:{cookie_source}"


def _build_tier3_env(config: Dict[str, Any]) -> Dict[str, str]:
    t3_cfg = config.get("tier3") or {}
    env = os.environ.copy()
    cookie_source = str(t3_cfg.get("cookie_source") or "config_file").strip().lower()

    if cookie_source in {"config_file", "env"}:
        if cookie_source == "config_file":
            env["TWITTER_AUTH_TOKEN"] = str(t3_cfg.get("auth_token") or "").strip()
            env["TWITTER_CT0"] = str(t3_cfg.get("ct0") or "").strip()
        else:
            env["TWITTER_AUTH_TOKEN"] = str(os.environ.get("TWITTER_AUTH_TOKEN") or "").strip()
            env["TWITTER_CT0"] = str(os.environ.get("TWITTER_CT0") or "").strip()

        env.pop("TWITTER_BROWSER", None)
        env.pop("TWITTER_CHROME_PROFILE", None)
        env.pop("PYTHONSAFEPATH", None)
        stub_dir = _ensure_browser_cookie3_stub(config)
        existing_pp = env.get("PYTHONPATH", "")
        env["PYTHONPATH"] = f"{stub_dir}{os.pathsep}{existing_pp}" if existing_pp else str(stub_dir)
    elif cookie_source == "browser":
        env.pop("TWITTER_AUTH_TOKEN", None)
        env.pop("TWITTER_CT0", None)
        browser_name = str(t3_cfg.get("browser_name") or "").strip()
        if browser_name:
            env["TWITTER_BROWSER"] = browser_name

    proxy = config.get("proxy")
    if proxy:
        env["TWITTER_PROXY"] = str(proxy)

    return env


def _should_trip_circuit_breaker(err_code: str, err_msg: str) -> bool:
    if err_code in _CIRCUIT_BREAKER_SAFE_CODES:
        return False
    if err_code in {"rate_limited", "not_authenticated"}:
        return True
    return bool(_CIRCUIT_BREAKER_MSG_RE.search(err_msg or ""))


def _run_twitter_cli_json(args: List[str], config: Dict[str, Any]) -> Any:
    ready, reason = check_tier3_readiness(config)
    if not ready:
        raise TierError("tier3_unavailable", reason)

    t3_cfg = config.get("tier3") or {}
    twitter_bin, bin_err = _resolve_twitter_bin(t3_cfg)
    if not twitter_bin:
        raise TierError("tier3_unavailable", bin_err)

    min_interval = cfg_float(t3_cfg, "min_interval_seconds", 2.5)
    timeout = cfg_int(t3_cfg, "timeout_seconds", 50)
    cooldown = cfg_int(t3_cfg, "circuit_breaker_cooldown_seconds", 900)
    lock_path = _state_lock_path(config)

    wait_s = 0.0
    with _StateFileLock(lock_path):
        state = _load_tier3_state(config)
        now = time.time()
        cooldown_until = float(state.get("cooldown_until") or 0)
        if cooldown_until > now:
            raise TierError("tier3_unavailable", f"circuit_breaker_open:{int(cooldown_until - now)}s")

        last_call = float(state.get("last_call_ts") or 0)
        elapsed = now - last_call
        if last_call > 0 and min_interval > 0 and elapsed < min_interval:
            wait_s = (min_interval - elapsed) + random.uniform(0.05, 0.5)
        state["last_call_ts"] = now + wait_s
        _save_tier3_state(config, state)

    if wait_s > 0:
        time.sleep(wait_s)
        post_sleep_state = _load_tier3_state(config)
        cooldown_until = float(post_sleep_state.get("cooldown_until") or 0)
        now = time.time()
        if cooldown_until > now:
            raise TierError("tier3_unavailable", f"circuit_breaker_open:{int(cooldown_until - now)}s")

    cmd = [twitter_bin, *args, "--json"]
    try:
        proc = subprocess.run(
            cmd,
            env=_build_tier3_env(config),
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=timeout,
        )
    except subprocess.TimeoutExpired as exc:
        raise TierError("tier3_timeout", f"twitter-cli timed out after {timeout}s") from exc
    except OSError as exc:
        raise TierError("tier3_exec_error", f"Failed to execute twitter-cli: {exc}") from exc

    stdout = (proc.stdout or "").strip()
    stderr = (proc.stderr or "").strip()
    payload: Optional[Dict[str, Any]] = None
    if stdout:
        try:
            parsed = json.loads(stdout)
            if isinstance(parsed, dict):
                payload = parsed
        except json.JSONDecodeError:
            payload = None

    if proc.returncode != 0 or not isinstance(payload, dict) or not payload.get("ok"):
        raw_err = (payload or {}).get("error")
        if isinstance(raw_err, dict):
            err_code = str(raw_err.get("code") or "tier3_failed")
            err_msg = str(raw_err.get("message") or stderr or stdout or f"exit code {proc.returncode}")
        elif isinstance(raw_err, str) and raw_err.strip():
            err_code = "tier3_failed"
            err_msg = raw_err.strip()
        else:
            err_code = "tier3_failed"
            err_msg = stderr or stdout or f"exit code {proc.returncode}"

        if _should_trip_circuit_breaker(err_code, err_msg):
            with _StateFileLock(lock_path):
                fresh = _load_tier3_state(config)
                fresh["cooldown_until"] = max(float(fresh.get("cooldown_until") or 0), time.time() + cooldown)
                fresh["last_error"] = f"{err_code}: {err_msg}"
                _save_tier3_state(config, fresh)
        raise TierError(err_code, err_msg)

    return payload.get("data")


def _parse_twitter_cli_tweet(item: Dict[str, Any]) -> PostItem:
    author = item.get("author") or {}
    metrics = item.get("metrics") or {}
    media_list: List[MediaItem] = []
    for m in item.get("media") or []:
        if isinstance(m, dict) and m.get("url"):
            media_list.append(MediaItem(type=str(m.get("type") or "media"), url=str(m["url"])))

    article_data: Optional[ArticleData] = None
    if item.get("articleTitle") or item.get("articleText"):
        article_data = ArticleData(
            title=str(item.get("articleTitle") or ""),
            blocks_markdown=str(item.get("articleText") or ""),
            has_complex_blocks=False,
        )

    quoted_raw = item.get("quotedTweet")
    quoted_item = _parse_twitter_cli_tweet(quoted_raw) if isinstance(quoted_raw, dict) else None
    tweet_id = str(item.get("id") or "")
    handle = str(author.get("screenName") or "unknown")

    return PostItem(
        id=tweet_id,
        url=f"https://x.com/{handle}/status/{tweet_id}" if tweet_id else "",
        author_id=str(author.get("id") or ""),
        author_handle=handle,
        author_name=str(author.get("name") or handle),
        created_at=str(item.get("createdAtISO") or item.get("createdAt") or ""),
        text=str(item.get("text") or ""),
        is_note_tweet=len(str(item.get("text") or "")) > 280,
        article=article_data,
        quote=quoted_item,
        media=media_list,
        stats={
            "replies": metrics.get("replies") or 0,
            "retweets": metrics.get("retweets") or 0,
            "likes": metrics.get("likes") or 0,
            "views": metrics.get("views"),
            "bookmarks": metrics.get("bookmarks"),
        },
        is_retweet=bool(item.get("isRetweet")),
    )


def fetch_tier3_thread(tweet_id: str, config: Dict[str, Any]) -> List[PostItem]:
    """Fetch focal tweet + conversation tweets via twitter-cli."""
    max_tweets = cfg_int(config.get("tier3") or {}, "max_thread_tweets", 50)
    data = _run_twitter_cli_json(["tweet", tweet_id, "--max", str(max_tweets)], config)
    if not isinstance(data, list):
        raise TierError("tier3_empty", f"twitter-cli returned no tweets for {tweet_id}")
    posts = [_parse_twitter_cli_tweet(entry) for entry in data if isinstance(entry, dict)]
    if not posts:
        raise TierError("tier3_empty", f"twitter-cli returned no tweets for {tweet_id}")
    return posts


def fetch_tier3_article(tweet_id: str, config: Dict[str, Any]) -> PostItem:
    """Fetch full X Article via twitter-cli."""
    data = _run_twitter_cli_json(["article", tweet_id], config)
    if not isinstance(data, dict):
        raise TierError("tier3_empty", f"twitter-cli returned invalid article payload for {tweet_id}")
    return _parse_twitter_cli_tweet(data)


def verify_tier3_auth(config: Dict[str, Any]) -> Dict[str, Any]:
    """Run live `twitter status --json` to confirm configured Tier 3 credentials are active."""
    data = _run_twitter_cli_json(["status"], config)
    return data if isinstance(data, dict) else {}
