    media: List[MediaItem] = field(default_factory=list)
    poll: Optional[Dict[str, Any]] = None
    replying_to: Optional[str] = None
    replying_to_status: Optional[str] = None
    stats: Dict[str, Any] = field(default_factory=dict)
