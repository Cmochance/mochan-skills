@dataclass
class TargetSpec:
    """Normalized X post / article target parsed from URL or raw ID."""

    tweet_id: str
    user_hint: str
    is_article_url: bool
    canonical_url: str


@dataclass
class MediaItem:
    """Normalized media attachment."""

    type: str
    url: str
    alt_text: str = ""


@dataclass
class ArticleData:
    """Normalized X Article payload."""

    title: str
    preview_text: str = ""
    blocks_markdown: str = ""
    cover_url: str = ""
    has_complex_blocks: bool = False


@dataclass
class PostItem:
    """Unified tweet/post representation shared across Tier 1 and Tier 3."""

    id: str
    url: str
    author_id: str
    author_handle: str
